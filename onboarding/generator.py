def _svc_yaml(name: str, namespace: str, selector: dict,
              port: int, target_port: int, node_port: int) -> str:
    sel_lines = "\n".join(f"    {k}: {v}" for k, v in selector.items())
    return textwrap.dedent(f"""\
    apiVersion: v1
    kind: Service
    metadata:
      name: {name}
      namespace: {namespace}
    spec:
      type: NodePort
      selector:
    {sel_lines}
      ports:
      - {{name: http, port: {port}, targetPort: {target_port}, nodePort: {node_port}}}
    """)


def generate_expose(system_id: str, namespace: str,
                    jaeger_svc: ServiceMatch | None,
                    prometheus_svc: ServiceMatch | None,
                    frontend_svc: ServiceMatch | None,
                    node_ports: list[int]) -> str:
    """生成 benchmarks/target_systems/<system_id>/expose.sh"""
    lines = [
        "#!/usr/bin/env bash",
        f"# Auto-generated expose script for {system_id}",
        "# Generated by: python cli.py onboard",
        "set -euo pipefail",
        'export KUBECONFIG="${KUBECONFIG:-/home/xueht/new-sesora/kubeconfig}"',
        f'NS={namespace}',
        'HERE="$(cd "$(dirname "$0")" && pwd)"',
        'MDIR="$HERE/manifests"',
        'mkdir -p "$MDIR"',
        "",
        "# 1. Create NodePort Services (idempotent)",
        "kubectl apply -f - <<'EOF'",
    ]

    port_idx = 0
    exposed_info = []

    if jaeger_svc and port_idx < len(node_ports):
        np = node_ports[port_idx]
        lines.append(_svc_yaml(
            f"jaeger-cnaa-{system_id}", namespace,
            jaeger_svc.selector, jaeger_svc.port,
            jaeger_svc.target_port, np))
        exposed_info.append(f"jaeger={np}")
        port_idx += 1

    if prometheus_svc and port_idx < len(node_ports):
        np = node_ports[port_idx]
        lines.append(_svc_yaml(
            f"prometheus-cnaa-{system_id}", namespace,
            prometheus_svc.selector, prometheus_svc.port,
            prometheus_svc.target_port, np))
        exposed_info.append(f"prometheus={np}")
        port_idx += 1

    if frontend_svc and port_idx < len(node_ports):
        np = node_ports[port_idx]
        lines.append(_svc_yaml(
            f"frontend-cnaa-{system_id}", namespace,
            frontend_svc.selector, frontend_svc.port,
            frontend_svc.target_port, np))
        exposed_info.append(f"frontend={np}")
        port_idx += 1

    lines.append("EOF")
    lines.append("")

    # 2. Export live manifests
    lines.extend([
        "# 2. Export live manifests (DESIRED_CONFIG snapshot)",
        'for d in $(kubectl get deploy -n "$NS" -o name); do',
        '  n="${d#deployment.apps/}"',
        '  kubectl get "$d" -n "$NS" -o yaml > "$MDIR/deployment-$n.yaml"',
        "done",
        'for s in $(kubectl get svc -n "$NS" -o name); do',
        '  n="${s#service/}"',
        '  kubectl get "$s" -n "$NS" -o yaml > "$MDIR/service-$n.yaml"',
        "done",
        'for d in $(kubectl get ds -n "$NS" -o name 2>/dev/null); do',
        '  n="${d#daemonset.apps/}"',
        '  kubectl get "$d" -n "$NS" -o yaml > "$MDIR/daemonset-$n.yaml"',
        "done",
        'for s in $(kubectl get sts -n "$NS" -o name 2>/dev/null); do',
        '  n="${s#statefulset.apps/}"',
        '  kubectl get "$s" -n "$NS" -o yaml > "$MDIR/statefulset-$n.yaml"',
        "done",
        "",
        f'echo "exposed: {" ".join(exposed_info)}"',
        'echo "manifests exported: $MDIR ($(ls "$MDIR" | wc -l) files)"',
    ])

    return "\n".join(lines) + "\n"
