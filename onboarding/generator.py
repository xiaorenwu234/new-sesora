# ---------------------------------------------------------------------------

def generate_profile(system_id: str, namespace: str,
                     classification: Classification) -> str:
    """生成 benchmarks/systems/<system_id>.yaml"""
    lines = [
        f"# Auto-generated system profile for {system_id}",
        f"# Generated by: python cli.py onboard",
        f"system_id: {system_id}",
        f"namespace: {namespace}",
        "source_root: src",
        "",
    ]

    if classification.critical_services:
        lines.append("critical_services:")
        for s in classification.critical_services:
            lines.append(f"  - {s}")
        lines.append("")

    if classification.stateful_services:
        lines.append("stateful_services:")
        for s in classification.stateful_services:
            lines.append(f"  - {s}")
        lines.append("")

    if classification.infra_services:
        lines.append("infra_services:")
        for s in classification.infra_services:
            lines.append(f"  - {s}")
        lines.append("")

    if classification.write_operations:
        lines.append("write_operations:")
        for svc, ops in sorted(classification.write_operations.items()):
            lines.append(f"  {svc}:")
            for op in ops:
                lines.append(f"    - {{op: {op['op']}, store: {op['store']}, "
                             f"idempotent: {op['idempotent']}}}")
        lines.append("")

    lines.append("service_mapping:")
    for name in sorted(classification.service_mapping):
        entry = classification.service_mapping[name]
        src = entry.get("source_dir") or "null"
        lines.append(f"  {name}: {{deployment: {entry['deployment']}, "
                      f"otel_name: {entry['otel_name']}, source_dir: {src}}}")

    return "\n".join(lines) + "\n"


